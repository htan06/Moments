CREATE SCHEMA content;

CREATE TYPE content.visibility AS ENUM (
  'PRIVATE',
  'PUBLIC',
  'FRIEND'
);

CREATE TYPE content.media_type AS ENUM (
  'IMAGE',
  'VIDEO'
);

CREATE TYPE content.aspect_ratio AS ENUM (
  '1:1',
  '3:2',
  '4:3',
  '3:4',
  '16:9'
);

CREATE TYPE content.post_status AS enum (
  'PENDING',
  'PUBLISHED',
  'DELETED'
);

CREATE TABLE content.posts (
  id bigint GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
  author_id bigint NOT NULL,
  content JSONB NOT NULL,
  visibility content.visibility NOT NULL,
  thumbnail_key text NOT NULL,
  media_count int NOT NULL,
  aspect_ratio content.aspect_ratio NOT NULL,
  like_count bigint NOT NULL DEFAULT 0,
  comment_count int NOT NULL DEFAULT 0,
  status content.post_status,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE content.post_mentions (
  post_id bigint NOT NULL,
  user_id bigint NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (post_id, user_id)
);

CREATE TABLE content.reposts (
  id bigint GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
  user_id bigint NOT NULL,
  post_id bigint NOT NULL,
  create_ad timestamptz DEFAULT CURRENT_TIMESTAMP,
  
  UNIQUE (user_id, post_id)
);

CREATE TABLE content.hashtags (
  id bigint GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
  tag_name text NOT NULL UNIQUE,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE content.post_hashtags (
  post_id bigint NOT NULL,
  hashtag_id bigint NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (post_id, hashtag_id)
);

CREATE TABLE content.medias (
  id bigint GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
  post_id bigint NOT NULL,
  type content.media_type NOT NULL,
  media_key text NOT NULL,
  display_order int NOT NULL,
  width int NOT NULL,
  height int NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE content.comments (
  id bigint GENERATED BY DEFAULT AS IDENTITY  PRIMARY KEY,
  author_id bigint NOT NULL,
  post_id bigint NOT NULL,
  parent_comment_id bigint,
  content text NOT NULL,
  reply_count int NOT NULL DEFAULT 0,
  like_count int NOT NULL DEFAULT 0,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE content.comment_mentions (
  comment_id bigint NOT NULL,
  user_id bigint NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,

  PRIMARY KEY (comment_id, user_id)
);

CREATE TABLE content.post_likes (
  user_id bigint NOT NULL,
  post_id bigint NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, post_id)
);

CREATE TABLE content.comment_likes (
  user_id bigint NOT NULL,
  comment_id bigint NOT NULL,
  created_at timestamptz DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, comment_id)
);

CREATE TABLE content.authors (
  user_id bigint PRIMARY KEY,
  username varchar UNIQUE NOT NULL,
  name varchar NOT NULL,
  avatar_thumbnail_key text,
  updated_at timestamptz DEFAULT CURRENT_TIMESTAMP
);
